import { NextRequest, NextResponse } from 'next/server';
import { getSupabaseAdmin } from '@/lib/supabase';
import { verifyAdminApiSession } from '@/lib/admin-auth';
import { logRevenueAuditEvent } from '@/lib/revenue-db';

export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const auth = await verifyAdminApiSession();
    if (!auth.authorized) return auth.response!;

    const { id } = await params;
    const admin = getSupabaseAdmin();

    const { data: plan, error } = await admin
      .from('subscription_plans')
      .select('*')
      .or(`id.eq.${id},slug.eq.${id}`)
      .maybeSingle();

    if (error || !plan) {
      return NextResponse.json({ error: 'Plan not found' }, { status: 404 });
    }

    // Active subscribers count for this plan
    const { count: subscriberCount } = await admin
      .from('subscriptions')
      .select('*', { count: 'exact', head: true })
      .or(`plan_id.eq.${plan.id},plan_id.eq.${plan.slug}`)
      .eq('status', 'active');

    // Revenue generated by this plan
    const { data: payments } = await admin
      .from('payments')
      .select('amount')
      .or(`plan_id.eq.${plan.id},plan_id.eq.${plan.slug}`)
      .eq('status', 'captured');

    const totalRevenue = (payments || []).reduce((sum: number, p: any) => sum + (Number(p.amount) || 0), 0);

    return NextResponse.json({
      success: true,
      plan: {
        ...plan,
        subscribers_count: subscriberCount || 0,
        total_revenue: totalRevenue,
      },
    });
  } catch (error: any) {
    return NextResponse.json({ error: error.message || 'Server error' }, { status: 500 });
  }
}

export async function PATCH(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const auth = await verifyAdminApiSession();
    if (!auth.authorized) return auth.response!;

    const { id } = await params;
    const body = await req.json();

    const admin = getSupabaseAdmin();
    const updatePayload = {
      ...body,
      updated_at: new Date().toISOString(),
    };

    const { data: updatedPlan, error } = await admin
      .from('subscription_plans')
      .update(updatePayload)
      .or(`id.eq.${id},slug.eq.${id}`)
      .select()
      .single();

    if (error) {
      return NextResponse.json({ error: error.message }, { status: 400 });
    }

    await logRevenueAuditEvent({
      userId: auth.user?.id || 'admin',
      action: 'UPDATE_PLAN',
      entityType: 'subscription_plans',
      entityId: id,
      details: body,
    });

    return NextResponse.json({ success: true, plan: updatedPlan });
  } catch (error: any) {
    return NextResponse.json({ error: error.message || 'Server error' }, { status: 500 });
  }
}

export async function DELETE(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const auth = await verifyAdminApiSession();
    if (!auth.authorized) return auth.response!;

    const { id } = await params;
    const admin = getSupabaseAdmin();

    // Soft delete / archive
    const { data, error } = await admin
      .from('subscription_plans')
      .update({ is_active: false, updated_at: new Date().toISOString() })
      .or(`id.eq.${id},slug.eq.${id}`)
      .select()
      .single();

    if (error) {
      return NextResponse.json({ error: error.message }, { status: 400 });
    }

    await logRevenueAuditEvent({
      userId: auth.user?.id || 'admin',
      action: 'ARCHIVE_PLAN',
      entityType: 'subscription_plans',
      entityId: id,
      details: { is_active: false },
    });

    return NextResponse.json({ success: true, message: 'Plan deactivated successfully' });
  } catch (error: any) {
    return NextResponse.json({ error: error.message || 'Server error' }, { status: 500 });
  }
}
